// The core stack's logos (owner, 19 Nov 2026: the 19 he's strongest in), from Simple Icons.
//
// Run by hand when the list or the icons change:
//   node scripts/stack-icons.mjs <simple-icons package folder> [<tanawat011 profile repo>]
// (get the folder with `npm pack simple-icons` and untar it; it's not a dependency of the site.)
//
// Writes content/stack-icons.ts (the paths and colours the portfolio draws inline) and, given the profile repo, its
// assets/stack/<id>-dark.svg and -light.svg badges and assets/stack/NOTICE.md.
//
// Colours: each brand's own, nudged only as far as needed to reach 3:1 against the tile it sits on (lighter in the
// dark theme, darker in the light one). A near-black mark (Next.js, Vercel, Express, shadcn/ui, Rust) takes the
// theme's ink instead, as those brands draw it.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const [pkg, profile] = process.argv.slice(2);
if (!pkg) throw new Error("usage: node scripts/stack-icons.mjs <simple-icons package folder> [<profile repo>]");
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** His 19, in the order the portfolio shows them; id = file name, icon = Simple Icons slug. */
export const ITEMS = [
  ["TypeScript", "typescript"], ["Rust", "rust"],
  ["React", "react"], ["Next.js", "nextdotjs"], ["Tailwind CSS", "tailwindcss"], ["Ant Design", "antdesign"], ["shadcn/ui", "shadcnui"],
  ["React Native", "react"], ["Flutter", "flutter"],
  ["Node.js", "nodedotjs"], ["NestJS", "nestjs"], ["Express", "express"],
  ["PostgreSQL", "postgresql"], ["MongoDB", "mongodb"], ["Supabase", "supabase"], ["Vercel", "vercel"],
  ["Docker", "docker"], ["Vitest", "vitest"], ["Claude Code", "claude"],
].map(([name, icon]) => ({ name, icon, id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/-$/, "") }));

const data = JSON.parse(readFileSync(join(pkg, "data/simple-icons.json"), "utf8"));
const all = Array.isArray(data) ? data : data.icons;
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
const slugOf = (i) => i.slug ?? i.title.toLowerCase().replace(/\+/g, "plus").replace(/\./g, "dot").replace(/&/g, "and").replace(/[^a-z0-9]/g, "");

const rgb = (h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
const hex = (c) => c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();
const lum = (h) => {
  const [r, g, b] = rgb(h).map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const mix = (a, b, t) => hex(rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t));
/** the brand colour, moved toward `to` in 5 % steps until it reaches 3:1 on `bg` */
const tune = (brand, bg, to) => { for (let t = 0; t <= 1; t += 0.05) { const c = mix(brand, to, t); if (contrast(c, bg) >= 3) return c; } return to; };
const nearBlack = (h) => rgb(h).every((v) => v < 0x30);

// the tiles they sit on: the portfolio's (--card2, dark / light) and GitHub's (canvas subtle, dark / light)
const SITE = { dark: "15171C", light: "EEF0F3" };
const GH = { dark: "161B22", light: "F6F8FA" };

const icons = {};
for (const it of ITEMS) {
  if (icons[it.icon]) continue;
  const i = all.find((x) => slugOf(x) === it.icon);
  if (!i) throw new Error(`no icon ${it.icon}`);
  const path = readFileSync(join(pkg, "icons", `${it.icon}.svg`), "utf8").match(/ d="([^"]+)"/)[1];
  const ink = nearBlack(i.hex);
  icons[it.icon] = {
    title: i.title, hex: i.hex, path, license: i.license?.type ?? "CC0-1.0",
    site: { dark: ink ? "ink" : tune(i.hex, SITE.dark, "FFFFFF"), light: ink ? "ink" : tune(i.hex, SITE.light, "000000") },
    gh: { dark: ink ? "E6EDF3" : tune(i.hex, GH.dark, "FFFFFF"), light: ink ? "1F2328" : tune(i.hex, GH.light, "000000") },
  };
}

// 1 · the portfolio's data
const ts = `/**
 * The core stack's logos, from Simple Icons ${version} (simpleicons.org): generated by scripts/stack-icons.mjs, don't edit.
 * Shown to name the tools he uses (nominative use); names and logos belong to their owners. Simple Icons is CC0; the
 * Rust logo is the Rust Foundation's, CC BY-SA 4.0 (credited under the core stack).
 * dark / light: the fill on the tile in each theme ("ink" = the theme's own ink, for near-black marks).
 */
export interface StackIcon { title: string; path: string; license: string; dark: string; light: string }

export const STACK_ICONS: Record<string, StackIcon> = ${JSON.stringify(
  Object.fromEntries(Object.entries(icons).map(([k, v]) => [k, { title: v.title, path: v.path, license: v.license, dark: v.site.dark, light: v.site.light }])),
  null, 2,
)};
`;
writeFileSync(join(ROOT, "content/stack-icons.ts"), ts);

// 2 · the profile's badges: icon and name, in a mono face (predictable widths), one file per theme
if (profile) {
  const out = join(profile, "assets/stack");
  mkdirSync(out, { recursive: true });
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  for (const it of ITEMS) {
    const ic = icons[it.icon];
    for (const theme of ["dark", "light"]) {
      const W = Math.ceil(40 + it.name.length * 7.8 + 14);
      const bg = theme === "dark" ? { fill: "#161B22", stroke: "#30363D", text: "#E6EDF3" } : { fill: "#F6F8FA", stroke: "#D0D7DE", text: "#1F2328" };
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="34" viewBox="0 0 ${W} 34" role="img" aria-label="${esc(it.name)}"><title>${esc(it.name)}</title>` +
        `<rect x=".5" y=".5" width="${W - 1}" height="33" rx="9" fill="${bg.fill}" stroke="${bg.stroke}"/>` +
        `<svg x="12" y="8" width="18" height="18" viewBox="0 0 24 24"><path fill="#${ic.gh[theme]}" d="${ic.path}"/></svg>` +
        `<text x="40" y="21.6" font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,'Liberation Mono',monospace" font-size="13" font-weight="600" fill="${bg.text}">${esc(it.name)}</text></svg>\n`;
      writeFileSync(join(out, `${it.id}-${theme}.svg`), svg);
    }
  }
  writeFileSync(join(out, "NOTICE.md"), `# Core stack badges

Made by my-portfolio's scripts/stack-icons.mjs from [Simple Icons](https://simpleicons.org) ${version}. They're here
to name the tools I use; every name and logo belongs to its owner.

- Simple Icons is released under CC0 1.0.
- The Rust logo is the Rust Foundation's, under [CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/):
  \`rust-dark.svg\` and \`rust-light.svg\` are adaptations of it (recoloured, set on a badge), shared under the same
  licence.
- React Native's badge uses the React logo, which is React Native's own.
`);
}
